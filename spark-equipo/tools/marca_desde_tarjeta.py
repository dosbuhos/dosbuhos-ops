"""Builds public/marca.js (awards, where we are sold) from the QR card app, so Spark and the card say the same thing.
Run from spark-equipo/:  python3 tools/marca_desde_tarjeta.py   (after AWARDS or WHERE change in card/build_app.py)"""
import html, json, os, re
src = open(os.path.join(os.path.dirname(__file__), '..', '..', 'card', 'build_app.py'), encoding='utf-8').read()
def L(en, es=None): return (en, es or en)
ns = {'L': L}
i = src.index('AWARDS = ['); exec(src[i:src.index('\n]\n', i) + 3], ns)
i = src.index('WHERE = ['); exec(src[i:src.index('\n]\n', i) + 3], ns)
u = html.unescape
premios = [{'concurso': u(a['comp']), 'anio': a['year'], 'icono': a['icon'], 'vinos': [[u(w), m] for w, m in a['items']]} for a in ns['AWARDS']]
donde = []
for pais in ns['WHERE']:
    grupos = []
    for titulo, items in pais['rows']:
        if items and isinstance(items[0][0], tuple):   # grouped by region
            filas = [[u(r[1]), [x.strip() for x in u(txt).split(' · ')]] for r, txt in items]
        else:
            filas = [['', [u(x[1]) for x in items]]]
        grupos.append({'titulo': u(titulo[1]), 'filas': filas})
    donde.append({'pais': pais['es'], 'grupos': grupos})
corte = re.search(r'cut (\w+ \d+ \d{4})', src)
out = ('// Generated by tools/marca_desde_tarjeta.py from card/build_app.py. Do not edit by hand.\n'
       f'export const PREMIOS = {json.dumps(premios, ensure_ascii=False)};\n'
       f'export const DONDE = {json.dumps(donde, ensure_ascii=False)};\n')
open(os.path.join(os.path.dirname(__file__), '..', 'public', 'marca.js'), 'w', encoding='utf-8').write(out)
print(len(premios), 'concursos,', sum(len(p['vinos']) for p in premios), 'reconocimientos;', [(d['pais'], [(g['titulo'], sum(len(f[1]) for f in g['filas'])) for g in d['grupos']]) for d in donde])
