// Capturas móviles (iPhone 13) de los flujos principales para la revisión de UX.
import { chromium, devices } from 'playwright';
const BASE = process.env.BASE || 'http://localhost:8787';
const OUT = process.env.OUT || '/home/claude/shots/m';
const b = await chromium.launch(); const ctx = await b.newContext({ ...devices['iPhone 13'] }); const page = await ctx.newPage(); page.setDefaultTimeout(5000);
page.on('pageerror', (e) => console.log('PAGEERROR', e.message));
const shot = (n) => page.screenshot({ path: `${OUT}-${n}.png` });
const go = async (h) => { await page.goto(`${BASE}/#/${h}`); await page.waitForTimeout(700); };
await go('panel'); await shot('01-panel');
await go('tablero'); await shot('02-tablero');
await page.click('.seg button[data-v=pict]'); await page.waitForTimeout(300); await shot('03-tablero-bodega');
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight)); await page.waitForTimeout(200); await shot('04-tablero-bottom');
await go('operaciones'); await shot('05-operaciones');
await page.click('#newop'); await page.waitForTimeout(400); await shot('06-opmodal');
await page.click('.type-grid label:has(input[value=racking])'); await page.waitForTimeout(200);
await page.evaluate(() => { document.querySelector('#modal .modal-body').scrollTop = 380; }); await page.waitForTimeout(150); await shot('07-opmodal-racking');
await page.click('.vp[data-vp=o0] > button'); await page.waitForTimeout(300); await shot('08-picker');
await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
await go('tablero'); await page.click('.cell:not(.free)'); await page.waitForTimeout(700); await shot('09-recipiente');
await go('coupage'); await shot('10-coupage');
await go('depositos'); await shot('11-depositos');
await go('fermentaciones'); await shot('12-ferment');
await go('recepcion'); await page.click('#newr'); await page.waitForTimeout(400); await shot('13-recepcion-modal');
await page.keyboard.press('Escape');
await go('perfil'); await shot('14-perfil');
await go('inventario'); await shot('15-inventario');
await go('panel'); await page.click('#burger'); await page.waitForTimeout(300); await shot('16-menu');
await page.keyboard.press('Escape'); await page.keyboard.press('Control+k'); await page.waitForTimeout(300); await shot('17-cmdk');
await b.close(); console.log('shots ok');
