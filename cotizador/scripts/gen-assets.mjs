// Generates src/assets.js: fonts and logos as base64 so the PDF template is self-contained.
import { readFileSync, writeFileSync } from 'node:fs';
const b = p => readFileSync(new URL('../public/' + p, import.meta.url)).toString('base64');
const fonts = [
  ['Cormorant Garamond', 400, 'normal', 'fonts/cormorant-garamond-latin-400-normal.woff2'],
  ['Cormorant Garamond', 500, 'normal', 'fonts/cormorant-garamond-latin-500-normal.woff2'],
  ['Cormorant Garamond', 600, 'normal', 'fonts/cormorant-garamond-latin-600-normal.woff2'],
  ['Cormorant Garamond', 400, 'italic', 'fonts/cormorant-garamond-latin-400-italic.woff2'],
  ['Lato', 300, 'normal', 'fonts/lato-latin-300-normal.woff2'],
  ['Lato', 400, 'normal', 'fonts/lato-latin-400-normal.woff2'],
];
const css = fonts.map(([f, w, s, p]) => `@font-face{font-family:"${f}";font-weight:${w};font-style:${s};src:url(data:font/woff2;base64,${b(p)}) format("woff2")}`).join('\n');
const out = `// GENERATED by scripts/gen-assets.mjs — do not edit.\nexport const FONT_CSS = ${JSON.stringify(css)};\nexport const LOGO_DARK = "data:image/png;base64,${b('icons/logo-dark.png')}";\nexport const LOGO_LIGHT = "data:image/png;base64,${b('icons/logo-light.png')}";\n`;
writeFileSync(new URL('../src/assets.js', import.meta.url), out);
console.log('src/assets.js', (out.length / 1024).toFixed(0), 'KB');
